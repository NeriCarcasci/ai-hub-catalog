func ValidateAndStage(cfg Config) (Report, error) {
	var report Report
	var err error
	cfg, err = normalizeConfig(cfg)
	if err != nil {
		return report, err
	}
	var problems validationErrors

	runtimeFiles, err := readRuntimeFileList(cfg.RuntimeFileList)
	if err != nil {
		return report, err
	}

	catalogModels, catalogPayload, _, catalogCount, err := validateCatalogSources(cfg, runtimeFiles)
	problems.addErr(err)
	report.CatalogFiles = catalogCount

	benchmark, err := validateBenchmarks(cfg.BenchmarkDir, catalogModels)
	problems.addErr(err)
	problems.addErr(validateQualificationReport(cfg, benchmark, catalogPayload))
	report.BenchmarkFiles = benchmark.files
	report.BenchmarkModels = len(benchmark.modelIDs)

	if err := problems.err(); err != nil {
		return report, err
	}
	payload := validatedPayload{catalogs: catalogPayload, benchmarks: benchmark.payload}
	if err := stageAndVerifyPayload(cfg, payload); err != nil {
		return report, err
	}
	return report, nil
}

func normalizeConfig(cfg Config) (Config, error) {
	var err error
	if cfg.CatalogDir, err = resolveExistingDirectory("catalog", cfg.CatalogDir); err != nil {
		return cfg, err
	}
	if cfg.ProducerInputDir, err = resolveExistingDirectory("producer input", cfg.ProducerInputDir); err != nil {
		return cfg, err
	}
	if cfg.BenchmarkDir, err = resolveExistingDirectory("benchmark", cfg.BenchmarkDir); err != nil {
		return cfg, err
	}
	if cfg.BenchmarkQualificationReport, err = resolveExistingRegularFile("benchmark qualification report", cfg.BenchmarkQualificationReport); err != nil {
		return cfg, err
	}
	if cfg.RuntimeFileList, err = resolveExistingRegularFile("runtime catalog list", cfg.RuntimeFileList); err != nil {
		return cfg, err
	}
	if cfg.LoaderCheckDir, err = resolveExistingDirectory("Model Catalog loader check", cfg.LoaderCheckDir); err != nil {
		return cfg, err
	}
	if cfg.SupportedVersionList, err = resolveExistingRegularFile("supported Model Catalog version list", cfg.SupportedVersionList); err != nil {
		return cfg, err
	}
	if cfg.OutputDir, err = resolvePotentialPath(cfg.OutputDir); err != nil {
		return cfg, fmt.Errorf("resolve release-candidate output %q: %w", cfg.OutputDir, err)
	}

	inputs := []struct {
		name string
		path string
	}{
		{"catalog directory", cfg.CatalogDir},
		{"producer input directory", cfg.ProducerInputDir},
		{"benchmark directory", cfg.BenchmarkDir},
		{"benchmark qualification report", cfg.BenchmarkQualificationReport},
		{"runtime catalog list", cfg.RuntimeFileList},
		{"Model Catalog loader check directory", cfg.LoaderCheckDir},
		{"supported Model Catalog version list", cfg.SupportedVersionList},
	}
	for _, input := range inputs {
		if pathsOverlap(cfg.OutputDir, input.path) {
			return cfg, fmt.Errorf("release-candidate output %s overlaps %s %s", cfg.OutputDir, input.name, input.path)
		}
	}
	if pathContains(cfg.BenchmarkDir, cfg.BenchmarkQualificationReport) {
		return cfg, fmt.Errorf("benchmark qualification report must be outside benchmark payload directory %s", cfg.BenchmarkDir)
	}
	return cfg, nil
}

func resolveExistingDirectory(label, value string) (string, error) {
	resolved, info, err := resolveExistingPath(value)
	if err != nil {
		return "", fmt.Errorf("resolve %s directory %q: %w", label, value, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("%s path %s is not a directory", label, value)
	}
	return resolved, nil
}

func resolveExistingRegularFile(label, value string) (string, error) {
	resolved, info, err := resolveExistingPath(value)
	if err != nil {
		return "", fmt.Errorf("resolve %s %q: %w", label, value, err)
	}
	if !info.Mode().IsRegular() {
		return "", fmt.Errorf("%s %s is not a regular file", label, value)
	}
	return resolved, nil
}

func resolveExistingPath(value string) (string, fs.FileInfo, error) {
	if strings.TrimSpace(value) == "" {
		return "", nil, fmt.Errorf("path is empty")
	}
	abs, err := filepath.Abs(value)
	if err != nil {
		return "", nil, err
	}
	info, err := os.Lstat(abs)
	if err != nil {
		return "", nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return "", nil, fmt.Errorf("path itself is a symlink")
	}
	resolved, err := filepath.EvalSymlinks(abs)
	if err != nil {
		return "", nil, err
	}
	resolvedInfo, err := os.Stat(resolved)
	if err != nil {
		return "", nil, err
	}
	return filepath.Clean(resolved), resolvedInfo, nil
}

// resolvePotentialPath resolves every existing ancestor before appending missing
// components. All later writes use the resolved path, so a symlinked parent
// cannot redirect staging into an input tree after containment checks.
func resolvePotentialPath(value string) (string, error) {
	if strings.TrimSpace(value) == "" {
		return "", fmt.Errorf("path is empty")
	}
	abs, err := filepath.Abs(value)
	if err != nil {
		return "", err
	}
	if info, statErr := os.Lstat(abs); statErr == nil && info.Mode()&os.ModeSymlink != 0 {
		return "", fmt.Errorf("output path itself is a symlink")
	} else if statErr != nil && !os.IsNotExist(statErr) {
		return "", statErr
	}

	current := filepath.Clean(abs)
	var missing []string
	for {
		_, statErr := os.Lstat(current)
		if statErr == nil {
			break
		}
		if !os.IsNotExist(statErr) {
			return "", statErr
		}
		parent := filepath.Dir(current)
		if parent == current {
			return "", fmt.Errorf("no existing ancestor")
		}
		missing = append(missing, filepath.Base(current))
		current = parent
	}
	resolved, err := filepath.EvalSymlinks(current)
	if err != nil {
		return "", err
	}
	for i := len(missing) - 1; i >= 0; i-- {
		resolved = filepath.Join(resolved, missing[i])
	}
	resolved = filepath.Clean(resolved)
	if filepath.Dir(resolved) == resolved {
		return "", fmt.Errorf("refusing filesystem root")
	}
	return resolved, nil
}

func pathsOverlap(left, right string) bool {
	return pathContains(left, right) || pathContains(right, left)
}

func pathContains(parent, child string) bool {
	rel, err := filepath.Rel(parent, child)
	if err != nil {
		return false
	}
	return rel == "." || (rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)))
}

func runLoaderChecks(cfg Config) error {
	versions, err := readSupportedVersionList(cfg.SupportedVersionList)
	if err != nil {
		return err
	}

	entries, err := os.ReadDir(cfg.LoaderCheckDir)
	if err != nil {
		return fmt.Errorf("read Model Catalog loader check directory %s: %w", cfg.LoaderCheckDir, err)
	}
	checks := make(map[string]string, len(entries))
	for _, entry := range entries {
		checkPath := filepath.Join(cfg.LoaderCheckDir, entry.Name())
		if entry.IsDir() {
			return fmt.Errorf("model catalog loader check directory must not contain nested directory %s", checkPath)
		}
		info, err := os.Lstat(checkPath)
		if err != nil {
			return fmt.Errorf("inspect Model Catalog loader check %s: %w", checkPath, err)
		}
		if !info.Mode().IsRegular() || info.Mode().Perm()&0o111 == 0 {
			return fmt.Errorf("model catalog loader check %s must be a regular executable file", checkPath)
		}
		checks[entry.Name()] = checkPath
	}

	expected := make(map[string]struct{}, len(versions))
	for _, version := range versions {
		expected[version] = struct{}{}
	}
	var missing, extra []string
	for _, version := range versions {
		if _, exists := checks[version]; !exists {
			missing = append(missing, version)
		}
	}
	for version := range checks {
		if _, exists := expected[version]; !exists {
			extra = append(extra, version)
		}
	}
	if len(missing) > 0 || len(extra) > 0 {
		sort.Strings(extra)
		return fmt.Errorf("model catalog loader check membership does not match %s (missing: %v; extra: %v)", cfg.SupportedVersionList, missing, extra)
	}

	root, err := filepath.Abs(filepath.Join(cfg.OutputDir, "app"))
	if err != nil {
		return fmt.Errorf("resolve staged payload path: %w", err)
	}
	environment := append(os.Environ(),
		"RELEASE_CANDIDATE_ROOT="+root,
		"CATALOG_DATA_DIR="+filepath.Join(root, "data"),
		"BENCHMARK_DATA_DIR="+filepath.Join(root, "benchmarks"),
	)
	for _, version := range versions {
		check := checks[version]
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
		command := exec.CommandContext(ctx, check)
		command.Env = append(environment, "MODEL_CATALOG_VERSION="+version)
		command.WaitDelay = loaderCheckWaitDelay
		output, runErr := command.CombinedOutput()
		cancel()
		if ctx.Err() == context.DeadlineExceeded {
			return fmt.Errorf("model catalog loader check %s timed out after 5 minutes", version)
		}
		if runErr != nil {
			message := strings.TrimSpace(string(output))
			if message == "" {
				return fmt.Errorf("model catalog loader check %s failed: %w", version, runErr)
			}
			return fmt.Errorf("model catalog loader check %s failed: %w: %s", version, runErr, message)
		}
		attestation := "MODEL_CATALOG_LOADER_CHECK_OK=" + version
		foundAttestation := false
		for _, line := range strings.Split(strings.TrimSpace(string(output)), "\n") {
			if strings.TrimSpace(line) == attestation {
				foundAttestation = true
				break
			}
		}
		if !foundAttestation {
			return fmt.Errorf("model catalog loader check %s did not attest successful loading with %q", version, attestation)
		}
	}
	return nil
}

func readSupportedVersionList(path string) ([]string, error) {
	data, err := readRegularFile(path)
	if err != nil {
		return nil, err
	}
	seen := map[string]struct{}{}
	var versions []string
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		version := strings.TrimSpace(scanner.Text())
		if version == "" || strings.HasPrefix(version, "#") {
			continue
		}
		if !supportedVersionToken.MatchString(version) {
			return nil, fmt.Errorf("supported Model Catalog version %q must be a safe executable basename", version)
		}
		if _, exists := seen[version]; exists {
			return nil, fmt.Errorf("duplicate supported Model Catalog version %q", version)
		}
		seen[version] = struct{}{}
		versions = append(versions, version)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read supported Model Catalog version list %s: %w", path, err)
	}
	if len(versions) == 0 {
		return nil, fmt.Errorf("supported Model Catalog version list %s is empty; product release remains blocked pending an approved version matrix", path)
	}
	return versions, nil
}

func readRuntimeFileList(path string) ([]string, error) {
	data, err := readRegularFile(path)
	if err != nil {
		return nil, fmt.Errorf("read runtime catalog list %s: %w", path, err)
	}

	seen := map[string]struct{}{}
	var files []string
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if filepath.Base(line) != line || !strings.HasSuffix(line, "-catalog.yaml") {
			return nil, fmt.Errorf("runtime catalog entry %q must be a generated *-catalog.yaml basename", line)
		}
		if _, exists := seen[line]; exists {
			return nil, fmt.Errorf("duplicate runtime catalog entry %q", line)
		}
		seen[line] = struct{}{}
		files = append(files, line)
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read runtime catalog list %s: %w", path, err)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("runtime catalog list %s is empty", path)
	}
	return files, nil
}

func validateCatalogSources(cfg Config, runtimeFiles []string) (map[string]struct{}, map[string][]byte, map[string]string, int, error) {
	var problems validationErrors
	modelIDs := map[string]struct{}{}
	payload := make(map[string][]byte, len(runtimeFiles))
	modelIDsFolded := map[string]string{}
	catalogArtifacts := map[string]string{}
	modelCatalogArtifacts := map[string]map[string]string{}
	catalogAgentURLs := map[string]string{}
	collections := map[string]map[string]string{
		"models":           {},
		"mcp_servers":      {},
		"agents":           {},
		"serving_runtimes": {},
	}
	runtimeSet := make(map[string]struct{}, len(runtimeFiles))

	for _, name := range runtimeFiles {
		runtimeSet[name] = struct{}{}
		path := filepath.Join(cfg.CatalogDir, name)
		data, err := readRegularFile(path)
		if err != nil {
			problems.addErr(err)
			continue
		}
		payload[name] = bytes.Clone(data)
		if err := validateYAML(path, data); err != nil {
			problems.addErr(err)
			continue
		}
		var doc catalogDocument
		if err := yaml.Unmarshal(data, &doc); err != nil {
			problems.add("parse runtime catalog %s: %v", path, err)
			continue
		}
		if strings.TrimSpace(doc.Source) == "" {
			problems.add("runtime catalog %s has no source", path)
		}

		kind, entries, err := catalogEntries(doc)
		if err != nil {
			problems.add("runtime catalog %s: %v", path, err)
			continue
		}
		if kind == "models" {
			modelCatalogArtifacts[name] = map[string]string{}
		}
		for i, entry := range entries {
			id := strings.TrimSpace(entry.Name)
			if id == "" {
				problems.add("runtime catalog %s entry %d has no name", path, i+1)
				continue
			}
			if id != entry.Name {
				problems.add("runtime catalog %s entry %d name %q contains leading or trailing whitespace", path, i+1, entry.Name)
				continue
			}
			if first, exists := collections[kind][id]; exists {
				problems.add("duplicate %s identifier %q in %s and %s", kind, id, first, path)
			} else {
				collections[kind][id] = path
			}
			if kind == "models" {
				folded := strings.ToLower(id)
				if first, exists := modelIDsFolded[folded]; exists && first != id {
					problems.add("case-insensitive catalog model collision %q and %q", first, id)
				} else {
					modelIDsFolded[folded] = id
				}
				modelIDs[id] = struct{}{}
				for artifactIndex, artifact := range entry.Artifacts {
					uri := normalizeArtifactURI(artifact.URI)
					if uri == "" {
						problems.add("runtime catalog %s model %q artifact %d has no uri", path, id, artifactIndex+1)
						continue
					}
					if first, exists := catalogArtifacts[uri]; exists {
						problems.add("duplicate catalog artifact uri %q in %s and %s", uri, first, path)
					} else {
						catalogArtifacts[uri] = path
					}
					modelCatalogArtifacts[name][uri] = id
				}
			} else if kind == "agents" {
				repositoryURL := strings.TrimSpace(entry.RepositoryURL)
				if repositoryURL == "" {
					problems.add("runtime catalog %s agent %q has no repositoryUrl", path, id)
				} else if repositoryURL != entry.RepositoryURL {
					problems.add("runtime catalog %s agent %q repositoryUrl contains leading or trailing whitespace", path, id)
				} else if first, exists := catalogAgentURLs[repositoryURL]; exists {
					problems.add("duplicate agent repositoryUrl %q in %s and %s", repositoryURL, first, path)
				} else {
					catalogAgentURLs[repositoryURL] = path
				}
			}
		}
	}

	entries, err := os.ReadDir(cfg.CatalogDir)
	if err != nil {
		problems.add("read catalog directory %s: %v", cfg.CatalogDir, err)
	} else {
		for _, entry := range entries {
			path := filepath.Join(cfg.CatalogDir, entry.Name())
			if entry.Type()&os.ModeSymlink != 0 {
				problems.add("catalog directory contains symlink %s", path)
				continue
			}
			if entry.IsDir() || filepath.Ext(entry.Name()) != ".yaml" {
				continue
			}
			data, readErr := readRegularFile(path)
			if readErr != nil {
				problems.addErr(readErr)
				continue
			}
			problems.addErr(validateYAML(path, data))
			if strings.HasSuffix(entry.Name(), "-catalog.yaml") {
				if _, allowed := runtimeSet[entry.Name()]; !allowed {
					problems.add("generated catalog %s is not classified in the runtime allowlist", entry.Name())
				}
			}
		}
	}

	problems.addErr(validateProducerInputs(cfg.ProducerInputDir))
	problems.addErr(validateIndexes(cfg, collections, modelCatalogArtifacts, catalogAgentURLs))
	return modelIDs, payload, catalogAgentURLs, len(runtimeFiles), problems.err()
}

func catalogEntries(doc catalogDocument) (string, []namedCatalogEntry, error) {
	type candidate struct {
		kind    string
		entries []namedCatalogEntry
	}
	all := []candidate{
		{"models", doc.Models},
		{"mcp_servers", doc.MCPServers},
		{"agents", doc.Agents},
		{"serving_runtimes", doc.ServingRuntimes},
	}
	var found []candidate
	for _, item := range all {
		if item.entries != nil {
			found = append(found, item)
		}
	}
	if len(found) != 1 {
		return "", nil, fmt.Errorf("must contain exactly one supported top-level collection")
	}
	if len(found[0].entries) == 0 {
		return "", nil, fmt.Errorf("%s collection is empty", found[0].kind)
	}
	return found[0].kind, found[0].entries, nil
}

func validateProducerInputs(root string) error {
	var problems validationErrors
	info, err := os.Stat(root)
	if err != nil {
		return fmt.Errorf("read producer input directory %s: %w", root, err)
	}
	if !info.IsDir() {
		return fmt.Errorf("producer input path %s is not a directory", root)
	}
	err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			problems.add("walk producer input %s: %v", path, walkErr)
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			problems.add("producer input contains symlink %s", path)
			return nil
		}
		if entry.IsDir() || (filepath.Ext(path) != ".yaml" && filepath.Ext(path) != ".yml") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			problems.add("read producer input %s: %v", path, err)
			return nil
		}
		problems.addErr(validateYAML(path, data))
		return nil
	})
	problems.addErr(err)
	return problems.err()
}

func validateIndexes(cfg Config, catalogs map[string]map[string]string, modelCatalogArtifacts map[string]map[string]string, catalogAgentURLs map[string]string) error {
	var problems validationErrors
	catalogDir := cfg.CatalogDir
	indexedArtifacts := map[string]string{}
	pairedModelCatalogs := map[string]string{}
	indexedNames := map[string]map[string]string{
		"mcp_servers":      {},
		"serving_runtimes": {},
	}
	indexedAgentURLs := map[string]string{}
	supplementalArtifacts, err := readSupplementalModelArtifacts(cfg)
	problems.addErr(err)
	entries, err := os.ReadDir(catalogDir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), "-index.yaml") {
			continue
		}
		path := filepath.Join(catalogDir, entry.Name())
		data, err := readRegularFile(path)
		if err != nil {
			problems.addErr(err)
			continue
		}
		var doc indexDocument
		if err := yaml.Unmarshal(data, &doc); err != nil {
			problems.add("parse producer index %s: %v", path, err)
			continue
		}
		switch {
		case doc.Models != nil:
			catalogName := strings.TrimSuffix(entry.Name(), "-index.yaml") + "-catalog.yaml"
			catalogArtifacts, exists := modelCatalogArtifacts[catalogName]
			if !exists {
				problems.add("producer model index %s has no corresponding runtime catalog %s", path, filepath.Join(catalogDir, catalogName))
				catalogArtifacts = map[string]string{}
			} else if first, paired := pairedModelCatalogs[catalogName]; paired {
				problems.add("producer indexes %s and %s both correspond to model catalog %s", first, path, catalogName)
			} else {
				pairedModelCatalogs[catalogName] = path
			}
			pairSupplemental := map[string]string{}
			if catalogName == "models-catalog.yaml" {
				pairSupplemental = supplementalArtifacts
			}
			validateModelIndexPair(path, filepath.Join(catalogDir, catalogName), doc.Models, catalogArtifacts, pairSupplemental, indexedArtifacts, &problems)
		case doc.MCPServers != nil:
			validateLocalIndex(cfg, path, "mcp_servers", doc.MCPServers, catalogs["mcp_servers"], indexedNames["mcp_servers"], &problems)
		case doc.ServingRuntimes != nil:
			validateLocalIndex(cfg, path, "serving_runtimes", doc.ServingRuntimes, catalogs["serving_runtimes"], indexedNames["serving_runtimes"], &problems)
		case doc.Agents != nil:
			validateAgentIndex(path, doc, catalogAgentURLs, indexedAgentURLs, &problems)
		default:
			problems.add("producer index %s has no supported top-level collection", path)
		}
	}
	for catalogName := range modelCatalogArtifacts {
		if _, exists := pairedModelCatalogs[catalogName]; !exists {
			indexName := strings.TrimSuffix(catalogName, "-catalog.yaml") + "-index.yaml"
			problems.add("generated model catalog %s has no corresponding producer index %s", filepath.Join(catalogDir, catalogName), filepath.Join(catalogDir, indexName))
		}
	}
	if _, exists := modelCatalogArtifacts["models-catalog.yaml"]; !exists {
		for uri := range supplementalArtifacts {
			problems.add("supplemental catalog artifact %q is missing from generated model catalog %s", uri, filepath.Join(catalogDir, "models-catalog.yaml"))
		}
	}
	for _, kind := range []string{"mcp_servers", "serving_runtimes"} {
		for name, catalogPath := range catalogs[kind] {
			if _, exists := indexedNames[kind][name]; !exists {
				problems.add("generated %s name %q from %s is missing from all producer indexes", kind, name, catalogPath)
			}
		}
	}
	for repositoryURL, catalogPath := range catalogAgentURLs {
		if _, exists := indexedAgentURLs[repositoryURL]; !exists {
			problems.add("generated agent repositoryUrl %q from %s is missing from all producer indexes", repositoryURL, catalogPath)
		}
	}
	return problems.err()
}

func readSupplementalModelArtifacts(cfg Config) (map[string]string, error) {
	artifacts := map[string]string{}
	path := filepath.Join(cfg.ProducerInputDir, "supplemental-catalog.yaml")
	data, err := readRegularFile(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return artifacts, nil
		}
		return artifacts, err
	}
	if err := validateYAML(path, data); err != nil {
		return artifacts, err
	}
	var doc catalogDocument
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return artifacts, fmt.Errorf("parse supplemental catalog %s: %w", path, err)
	}
	kind, entries, err := catalogEntries(doc)
	if err != nil {
		return artifacts, fmt.Errorf("supplemental catalog %s: %w", path, err)
	}
	if kind != "models" {
		return artifacts, fmt.Errorf("supplemental catalog %s must contain a models collection", path)
	}

	var problems validationErrors
	for i, entry := range entries {
		modelName := strings.TrimSpace(entry.Name)
		if modelName == "" {
			problems.add("supplemental catalog %s model %d has no name", path, i+1)
		}
		if len(entry.Artifacts) == 0 {
			problems.add("supplemental catalog %s model %q has no artifacts", path, modelName)
		}
		for artifactIndex, artifact := range entry.Artifacts {
			uri := normalizeArtifactURI(artifact.URI)
			if uri == "" {
				problems.add("supplemental catalog %s model %q artifact %d has no uri", path, modelName, artifactIndex+1)
				continue
			}
			if first, exists := artifacts[uri]; exists {
				problems.add("supplemental catalog %s models %q and %q both contain artifact %q", path, first, modelName, uri)
				continue
			}
			artifacts[uri] = modelName
		}
	}
	return artifacts, problems.err()
}

func validateModelIndexPair(indexPath, catalogPath string, entries []modelIndexEntry, catalogArtifacts, supplementalArtifacts, indexedArtifacts map[string]string, problems *validationErrors) {
	if len(entries) == 0 {
		problems.add("producer index %s has an empty models collection", indexPath)
	}
	indexArtifacts := map[string]struct{}{}
	for i, item := range entries {
		uri := normalizeArtifactURI(item.URI)
		if uri == "" {
			problems.add("producer index %s model %d has no uri", indexPath, i+1)
			continue
		}
		if _, exists := indexArtifacts[uri]; exists {
			problems.add("producer index %s contains duplicate model artifact %q", indexPath, uri)
			continue
		}
		indexArtifacts[uri] = struct{}{}
		if first, exists := indexedArtifacts[uri]; exists {
			problems.add("producer indexes %s and %s both contain model artifact %q", first, indexPath, uri)
		} else {
			indexedArtifacts[uri] = indexPath
		}
		if _, exists := catalogArtifacts[uri]; !exists {
			problems.add("producer index %s artifact %q is missing from corresponding generated model catalog %s", indexPath, uri, catalogPath)
		}
	}

	for uri, supplementalModelName := range supplementalArtifacts {
		if _, exists := indexArtifacts[uri]; exists {
			problems.add("model artifact %q is declared by both producer index %s and supplemental catalog", uri, indexPath)
		}
		catalogModelName, exists := catalogArtifacts[uri]
		if !exists {
			problems.add("supplemental catalog artifact %q is missing from generated model catalog %s", uri, catalogPath)
		} else if catalogModelName != supplementalModelName {
			problems.add("supplemental catalog artifact %q belongs to model %q but generated model catalog %s assigns it to %q", uri, supplementalModelName, catalogPath, catalogModelName)
		}
	}
	for uri, modelName := range catalogArtifacts {
		if _, exists := indexArtifacts[uri]; exists {
			continue
		}
		if _, exists := supplementalArtifacts[uri]; exists {
			continue
		}
		problems.add("generated model catalog %s model %q artifact %q has no provenance in corresponding producer index %s or supplemental catalog", catalogPath, modelName, uri, indexPath)
	}
}

func validateAgentIndex(indexPath string, doc indexDocument, catalogAgentURLs, indexedAgentURLs map[string]string, problems *validationErrors) {
	if len(doc.Agents) == 0 {
		problems.add("producer index %s has an empty agents collection", indexPath)
		return
	}
	repository := strings.TrimSpace(doc.Repository)
	if repository == "" {
		problems.add("producer index %s has no repository", indexPath)
		return
	}
	if repository != doc.Repository {
		problems.add("producer index %s repository contains leading or trailing whitespace", indexPath)
		return
	}
	branch := strings.TrimSpace(doc.Branch)
	if branch == "" {
		branch = "main"
	} else if branch != doc.Branch {
		problems.add("producer index %s branch contains leading or trailing whitespace", indexPath)
		return
	}
	seen := map[string]struct{}{}
	for i, item := range doc.Agents {
		agentPath := strings.TrimSpace(item.Path)
		if agentPath == "" {
			problems.add("producer index %s agent %d has no path", indexPath, i+1)
			continue
		}
		if agentPath != item.Path || filepath.IsAbs(agentPath) || strings.Contains(agentPath, "\\") || filepath.Clean(agentPath) != agentPath || agentPath == "." || agentPath == ".." || strings.HasPrefix(agentPath, ".."+string(filepath.Separator)) {
			problems.add("producer index %s agent path %q must be a clean repository-relative path", indexPath, item.Path)
			continue
		}
		if _, exists := seen[agentPath]; exists {
			problems.add("producer index %s contains duplicate agent path %q", indexPath, agentPath)
			continue
		}
		seen[agentPath] = struct{}{}
		repositoryURL := fmt.Sprintf("https://github.com/%s/tree/%s/%s", repository, branch, agentPath)
		if first, exists := indexedAgentURLs[repositoryURL]; exists {
			problems.add("producer indexes %s and %s both contain agent repositoryUrl %q", first, indexPath, repositoryURL)
		} else {
			indexedAgentURLs[repositoryURL] = indexPath
		}
		if _, exists := catalogAgentURLs[repositoryURL]; !exists {
			problems.add("producer index %s agent path %q is missing from the generated agent catalogs", indexPath, agentPath)
		}
	}
}

func normalizeArtifactURI(uri string) string {
	uri = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(uri), "oci://"))
	if uri == "" {
		return ""
	}
	lastSlash := strings.LastIndex(uri, "/")
	if !strings.Contains(uri[lastSlash+1:], ":") && !strings.Contains(uri[lastSlash+1:], "@") {
		uri += ":latest"
	}
	return uri
}

func validateLocalIndex(cfg Config, path, kind string, entries []localIndexEntry, catalogNames, indexedNames map[string]string, problems *validationErrors) {
	seen := map[string]struct{}{}
	for i, item := range entries {
		name := strings.TrimSpace(item.Name)
		if name == "" {
			problems.add("producer index %s %s entry %d has no name", path, kind, i+1)
			continue
		}
		if _, exists := seen[name]; exists {
			problems.add("producer index %s contains duplicate %s name %q", path, kind, name)
		}
		seen[name] = struct{}{}
		if first, exists := indexedNames[name]; exists {
			problems.add("producer indexes %s and %s both contain %s name %q", first, path, kind, name)
		} else {
			indexedNames[name] = path
		}
		if strings.TrimSpace(item.InputPath) == "" {
			problems.add("producer index %s %q has no input_path", path, name)
		} else {
			resolved, err := resolveProducerReference(cfg, item.InputPath)
			if err != nil {
				problems.add("producer index %s %q input_path %s: %v", path, name, item.InputPath, err)
			} else if kind == "mcp_servers" {
				problems.addErr(validateMCPServerInputName(resolved, name))
			}
		}
		if _, exists := catalogNames[name]; !exists {
			problems.add("producer index %s name %q is missing from the generated %s catalogs", path, name, kind)
		}
	}
}

func resolveProducerReference(cfg Config, reference string) (string, error) {
	if filepath.IsAbs(reference) || strings.Contains(reference, "\\") {
		return "", fmt.Errorf("must be a portable repository-relative path")
	}
	clean := filepath.Clean(reference)
	if clean != reference || clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("must be a clean repository-relative path")
	}
	repositoryRoot := filepath.Dir(cfg.CatalogDir)
	resolved, err := resolveExistingRegularFile("producer input", filepath.Join(repositoryRoot, clean))
	if err != nil {
		return "", err
	}
	if !pathContains(cfg.ProducerInputDir, resolved) {
		return "", fmt.Errorf("resolves outside producer input directory %s", cfg.ProducerInputDir)
	}
	return resolved, nil
}

func validateMCPServerInputName(path, expected string) error {
	data, err := readRegularFile(path)
	if err != nil {
		return err
	}
	var metadata struct {
		Name string `yaml:"name"`
	}
	if err := yaml.Unmarshal(data, &metadata); err != nil {
		return fmt.Errorf("parse MCP server producer input %s: %w", path, err)
	}
	if metadata.Name != expected {
		return fmt.Errorf("MCP server producer input %s declares name %q, expected index name %q", path, metadata.Name, expected)
	}
	return nil
}

func validateQualificationReport(cfg Config, benchmark benchmarkValidation, catalogPayload map[string][]byte) error {
	var problems validationErrors
	reportData, err := readRegularFile(cfg.BenchmarkQualificationReport)
	if err != nil {
		return err
	}
	var report qualificationReport
	if err := decodeSingleJSON(cfg.BenchmarkQualificationReport, reportData, &report); err != nil {
		return err
	}
	if report.Version != qualificationReportVersion {
		problems.add("benchmark qualification report version %q must be %q", report.Version, qualificationReportVersion)
	}
	if report.MatchPolicy != benchmarkMatchPolicy {
		problems.add("benchmark qualification report match_policy %q must be %q", report.MatchPolicy, benchmarkMatchPolicy)
	}
	if !cfg.FixtureOnly {
		if report.QualificationMode != "release" {
			problems.add("benchmark qualification report qualification_mode %q must be %q", report.QualificationMode, "release")
		}
		if !report.PromotionEligible {
			problems.add("benchmark qualification report promotion_eligible must be true")
		}
	}
	for label, revision := range map[string]string{
		"benchmark_revision": report.BenchmarkRevision,
		"catalog_revision":   report.CatalogRevision,
	} {
		if !immutableRevision.MatchString(revision) {
			problems.add("benchmark qualification report %s must be an immutable full 40- or 64-character lowercase hexadecimal revision", label)
		}
	}
	if report.Source.Revision != report.BenchmarkRevision {
		problems.add("benchmark qualification report source revision does not match benchmark_revision")
	}
	if report.Catalog.Revision != report.CatalogRevision {
		problems.add("benchmark qualification report catalog revision does not match catalog_revision")
	}

	expectedReviewStatus := "approved"
	if cfg.FixtureOnly {
		expectedReviewStatus = "fixture"
	}
	if report.Exclusions.ReviewStatus != expectedReviewStatus {
		problems.add("benchmark qualification report exclusion review_status %q must be %q", report.Exclusions.ReviewStatus, expectedReviewStatus)
	}
	if strings.TrimSpace(report.Exclusions.ReviewReference) == "" {
		problems.add("benchmark qualification report has no exclusion review_reference")
	}
	if !sha256Digest.MatchString(report.Exclusions.SHA256) {
		problems.add("benchmark qualification report exclusion sha256 must be a lowercase SHA-256 digest")
	}

	expectedCatalogFiles := map[string]struct{}{
		"other-models-catalog.yaml":     {},
		"validated-models-catalog.yaml": {},
	}
	seenCatalogFiles := map[string]struct{}{}
	for _, descriptor := range report.Catalog.Files {
		if _, duplicate := seenCatalogFiles[descriptor.Name]; duplicate {
			problems.add("benchmark qualification report contains duplicate catalog file %q", descriptor.Name)
			continue
		}
		seenCatalogFiles[descriptor.Name] = struct{}{}
		if _, expected := expectedCatalogFiles[descriptor.Name]; !expected {
			problems.add("benchmark qualification report contains unexpected catalog file %q", descriptor.Name)
			continue
		}
		data, exists := catalogPayload[descriptor.Name]
		if !exists {
			problems.add("benchmark qualification report catalog file %q is absent from the runtime payload", descriptor.Name)
			continue
		}
		if descriptor.SHA256 != digestBytes(data) {
			problems.add("benchmark qualification report catalog file %q sha256 does not match the runtime catalog", descriptor.Name)
		}
	}
	for name := range expectedCatalogFiles {
		if _, exists := seenCatalogFiles[name]; !exists {
			problems.add("benchmark qualification report is missing catalog file %q", name)
		}
	}

	manifestData, manifestExists := benchmark.payload["manifest.json"]
	if !manifestExists {
		problems.add("qualified benchmark payload has no manifest.json to verify against its report")
	} else if report.OutputManifestSHA256 != digestBytes(manifestData) {
		problems.add("benchmark qualification report output_manifest_sha256 does not match the qualified payload")
	}
	if report.PayloadSHA256 != digestPayload(benchmark.payload) {
		problems.add("benchmark qualification report payload_sha256 does not match the qualified payload")
	}
	if report.Payload.Files != benchmark.files {
		problems.add("benchmark qualification report payload file count %d does not match validated payload count %d", report.Payload.Files, benchmark.files)
	}
	if report.Payload.Models != len(benchmark.modelIDs) || report.Models.Included != len(benchmark.modelIDs) {
		problems.add("benchmark qualification report model counts do not match %d validated benchmark models", len(benchmark.modelIDs))
	}
	if !equalStrings(report.IncludedModelIDs, benchmark.modelIDs) {
		problems.add("benchmark qualification report included_model_ids do not match the validated benchmark models")
	}
	return problems.err()
}

func digestBytes(data []byte) string {
	digest := sha256.Sum256(data)
	return fmt.Sprintf("%x", digest)
}

func digestPayload(payload map[string][]byte) string {
	digest := sha256.New()
	names := make([]string, 0, len(payload))
	for name := range payload {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		_, _ = digest.Write([]byte(name))
		_, _ = digest.Write([]byte{0})
		_, _ = digest.Write(payload[name])
		_, _ = digest.Write([]byte{0})
	}
	return fmt.Sprintf("%x", digest.Sum(nil))
}

func equalStrings(left, right []string) bool {
	if len(left) != len(right) {
		return false
	}
	for i := range left {
		if left[i] != right[i] {
			return false
		}
	}
	return true
}

func validateBenchmarks(root string, catalogModels map[string]struct{}) (benchmarkValidation, error) {
	var problems validationErrors
	result := benchmarkValidation{payload: map[string][]byte{}}
	catalogModelsFolded := make(map[string]struct{}, len(catalogModels))
	for modelID := range catalogModels {
		catalogModelsFolded[strings.ToLower(modelID)] = struct{}{}
	}
	manifestPath := filepath.Join(root, "manifest.json")
	manifestData, err := readRegularFile(manifestPath)
	if err != nil {
		return result, err
	}
	var manifest benchmarkManifest
	if err := decodeSingleJSON(manifestPath, manifestData, &manifest); err != nil {
		problems.addErr(err)
	}
	if strings.TrimSpace(manifest.Version) == "" {
		problems.add("benchmark manifest %s has no version", manifestPath)
	}
	if len(manifest.Files) == 0 {
		problems.add("benchmark manifest %s has no files", manifestPath)
	}

	actual := map[string]struct{}{}
	metadataIDs := map[string]string{}
	foldedIDs := map[string]string{}
	providerIDs := map[string]string{}
	foldedProviderIDs := map[string]string{}
	modelProviders := map[string]string{}
	variantGroupIDs := map[string]string{}
	modelVariantGroups := map[string]string{}
	artifactIDs := map[string]string{}
	fileCount := 0

	err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			problems.add("walk benchmark input %s: %v", path, walkErr)
			return nil
		}
		if path == root {
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			problems.add("benchmark input contains symlink %s", path)
			return nil
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			problems.add("benchmark input contains non-regular file %s", path)
			return nil
		}

		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			problems.add("resolve benchmark path %s: %v", path, relErr)
			return nil
		}
		rel = filepath.ToSlash(rel)
		fileCount++
		if rel != "manifest.json" {
			actual[rel] = struct{}{}
		}
		if err := validateBenchmarkPath(rel); err != nil {
			problems.addErr(err)
			return nil
		}

		data, readErr := os.ReadFile(path)
		if readErr != nil {
			problems.add("read benchmark file %s: %v", path, readErr)
			return nil
		}
		result.payload[rel] = bytes.Clone(data)
		switch filepath.Base(rel) {
		case "manifest.json":
			// Already parsed above.
		case "provider.json":
			var doc idDocument
			if err := decodeSingleJSON(path, data, &doc); err != nil {
				problems.addErr(err)
			} else if strings.TrimSpace(doc.ID) == "" {
				problems.add("benchmark provider %s has no id", path)
			} else if doc.ID != strings.TrimSpace(doc.ID) {
				problems.add("benchmark provider %s id %q contains leading or trailing whitespace", path, doc.ID)
			} else if first, exists := providerIDs[doc.ID]; exists {
				problems.add("duplicate benchmark provider id %q in %s and %s", doc.ID, first, path)
			} else {
				providerIDs[doc.ID] = path
				folded := strings.ToLower(doc.ID)
				if first, exists := foldedProviderIDs[folded]; exists && first != doc.ID {
					problems.add("case-insensitive benchmark provider collision %q and %q", first, doc.ID)
				} else {
					foldedProviderIDs[folded] = doc.ID
				}
			}
		case "metadata.json":
			var doc modelMetadata
			if err := decodeSingleJSON(path, data, &doc); err != nil {
				problems.addErr(err)
				return nil
			}
			expected := strings.TrimSuffix(rel, "/metadata.json")
			if doc.ID == "" {
				problems.add("benchmark metadata %s has no id", path)
			} else if doc.ID != expected {
				problems.add("benchmark metadata %s id %q does not match its path %q", path, doc.ID, expected)
			}
			if first, exists := metadataIDs[doc.ID]; exists {
				problems.add("duplicate benchmark model id %q in %s and %s", doc.ID, first, path)
			} else if doc.ID != "" {
				metadataIDs[doc.ID] = path
			}
			folded := strings.ToLower(doc.ID)
			if first, exists := foldedIDs[folded]; exists && first != doc.ID {
				problems.add("case-insensitive benchmark model collision %q and %q", first, doc.ID)
			} else if doc.ID != "" {
				foldedIDs[folded] = doc.ID
			}
			if strings.TrimSpace(doc.ProviderID) == "" {
				problems.add("benchmark metadata %s has no provider_id", path)
			} else if doc.ProviderID != strings.TrimSpace(doc.ProviderID) {
				problems.add("benchmark metadata %s provider_id %q contains leading or trailing whitespace", path, doc.ProviderID)
			} else if doc.ID != "" {
				modelProviders[doc.ID] = doc.ProviderID
			}
			if doc.VariantGroupID != nil {
				variantID := strings.TrimSpace(*doc.VariantGroupID)
				if variantID == "" || variantID != *doc.VariantGroupID {
					problems.add("benchmark metadata %s has an invalid variant_group_id", path)
				} else if doc.ID != "" {
					modelVariantGroups[doc.ID] = variantID
				}
			}
		case "variant-groups.ndjson":
			validateNDJSON(path, data, false, "", artifactIDs, variantGroupIDs, &problems)
		default:
			expectedModel := strings.TrimSuffix(rel, "/"+filepath.Base(rel))
			validateNDJSON(path, data, true, expectedModel, artifactIDs, nil, &problems)
		}
		return nil
	})
	problems.addErr(err)

	for path := range actual {
		if _, exists := manifest.Files[path]; !exists {
			problems.add("benchmark file %s is missing from manifest.json", path)
		}
	}
	for path := range manifest.Files {
		clean := pathpkgClean(path)
		if clean != path || strings.Contains(path, "\\") || strings.HasPrefix(path, "/") {
			problems.add("benchmark manifest contains unsafe path %q", path)
			continue
		}
		if _, exists := actual[path]; !exists {
			problems.add("benchmark manifest lists missing file %s", path)
		}
		if !validManifestKind(path, manifest.Files[path]) {
			problems.add("benchmark manifest file %s has unsupported type %q", path, manifest.Files[path])
		}
	}

	for modelID, path := range metadataIDs {
		if _, exists := catalogModelsFolded[strings.ToLower(modelID)]; !exists {
			problems.add("benchmark model %q from %s is not present in the runtime model catalogs", modelID, path)
		}
	}
	for modelID, providerID := range modelProviders {
		if _, exists := providerIDs[providerID]; !exists {
			problems.add("benchmark model %q references missing provider %q", modelID, providerID)
		}
	}
	for modelID, variantID := range modelVariantGroups {
		if _, exists := variantGroupIDs[variantID]; !exists {
			problems.add("benchmark model %q references missing variant group %q", modelID, variantID)
		}
	}

	for rel := range actual {
		parts := strings.Split(rel, "/")
		if len(parts) == 3 && filepath.Ext(rel) == ".ndjson" {
			modelID := strings.Join(parts[:2], "/")
			if _, exists := metadataIDs[modelID]; !exists {
				problems.add("benchmark records %s have no sibling metadata.json", rel)
			}
		}
	}

	result.files = fileCount
	result.modelIDs = make([]string, 0, len(metadataIDs))
	for modelID := range metadataIDs {
		result.modelIDs = append(result.modelIDs, modelID)
	}
	sort.Strings(result.modelIDs)
	return result, problems.err()
}

