func validManifestKind(path, kind string) bool {
	base := filepath.Base(path)
	switch base {
	case "provider.json":
		return kind == "provider_metadata"
	case "metadata.json":
		return kind == "model_metadata" || kind == "model_validations"
	case "evaluations.ndjson":
		return kind == "model_evaluations"
	case "performance.ndjson":
		return kind == "performance_metrics"
	case "security-evaluations.ndjson":
		return kind == "security_evaluations"
	case "variant-groups.ndjson":
		return kind == "variant_groups"
	default:
		return false
	}
}

func validateBenchmarkPath(rel string) error {
	parts := strings.Split(rel, "/")
	switch {
	case rel == "manifest.json" || rel == "variant-groups.ndjson":
		return nil
	case len(parts) == 2 && parts[1] == "provider.json":
		return nil
	case len(parts) == 3 && parts[2] == "metadata.json":
		return nil
	case len(parts) == 3 && (parts[2] == "evaluations.ndjson" || parts[2] == "performance.ndjson" || parts[2] == "security-evaluations.ndjson"):
		return nil
	default:
		return fmt.Errorf("unexpected benchmark file %s", rel)
	}
}

func validateNDJSON(path string, data []byte, requireModel bool, expectedModel string, artifactIDs, collectedIDs map[string]string, problems *validationErrors) {
	scanner := bufio.NewScanner(bytes.NewReader(data))
	scanner.Buffer(make([]byte, 64*1024), 16*1024*1024)
	line := 0
	records := 0
	for scanner.Scan() {
		line++
		raw := bytes.TrimSpace(scanner.Bytes())
		if len(raw) == 0 {
			continue
		}
		records++
		var record benchmarkRecord
		if err := decodeSingleJSON(fmt.Sprintf("%s:%d", path, line), raw, &record); err != nil {
			problems.addErr(err)
			continue
		}
		if strings.TrimSpace(record.ID) == "" {
			problems.add("benchmark record %s:%d has no id", path, line)
		} else if first, exists := artifactIDs[record.ID]; exists {
			problems.add("duplicate benchmark artifact id %q in %s and %s:%d", record.ID, first, path, line)
		} else {
			artifactIDs[record.ID] = fmt.Sprintf("%s:%d", path, line)
			if collectedIDs != nil {
				collectedIDs[record.ID] = fmt.Sprintf("%s:%d", path, line)
			}
		}
		if requireModel {
			if strings.TrimSpace(record.ModelID) == "" {
				problems.add("benchmark record %s:%d has no model_id", path, line)
			} else if record.ModelID != expectedModel {
				problems.add("benchmark record %s:%d model_id %q does not match path model %q", path, line, record.ModelID, expectedModel)
			}
		}
	}
	if err := scanner.Err(); err != nil {
		problems.add("read benchmark NDJSON %s: %v", path, err)
	}
	if records == 0 {
		problems.add("benchmark NDJSON %s contains no records", path)
	}
}

func validateYAML(path string, data []byte) error {
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	var doc yaml.Node
	if err := decoder.Decode(&doc); err != nil {
		return fmt.Errorf("parse YAML %s: %w", path, err)
	}
	if len(doc.Content) == 0 {
		return fmt.Errorf("yaml file %s is empty", path)
	}
	if err := validateYAMLMappingKeys(doc.Content[0]); err != nil {
		return fmt.Errorf("parse YAML %s: %w", path, err)
	}
	var extra yaml.Node
	if err := decoder.Decode(&extra); err != io.EOF {
		if err == nil {
			return fmt.Errorf("yaml file %s contains multiple documents", path)
		}
		return fmt.Errorf("parse YAML %s: %w", path, err)
	}
	return nil
}

func validateYAMLMappingKeys(node *yaml.Node) error {
	if node.Kind == yaml.MappingNode {
		seen := map[string]struct{}{}
		for i := 0; i < len(node.Content); i += 2 {
			key := node.Content[i].Value
			if _, exists := seen[key]; exists {
				return fmt.Errorf("duplicate mapping key %q at line %d", key, node.Content[i].Line)
			}
			seen[key] = struct{}{}
		}
	}
	for _, child := range node.Content {
		if err := validateYAMLMappingKeys(child); err != nil {
			return err
		}
	}
	return nil
}

func decodeSingleJSON(path string, data []byte, target any) error {
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	if err := validateJSONValue(decoder); err != nil {
		return fmt.Errorf("parse JSON %s: %w", path, err)
	}
	if _, err := decoder.Token(); err != io.EOF {
		if err == nil {
			return fmt.Errorf("json file %s contains multiple values", path)
		}
		return fmt.Errorf("parse JSON %s: %w", path, err)
	}
	if err := json.Unmarshal(data, target); err != nil {
		return fmt.Errorf("parse JSON %s: %w", path, err)
	}
	return nil
}

func validateJSONValue(decoder *json.Decoder) error {
	token, err := decoder.Token()
	if err != nil {
		return err
	}
	delimiter, ok := token.(json.Delim)
	if !ok {
		return nil
	}

	switch delimiter {
	case '{':
		seen := map[string]struct{}{}
		for decoder.More() {
			keyToken, err := decoder.Token()
			if err != nil {
				return err
			}
			key, ok := keyToken.(string)
			if !ok {
				return fmt.Errorf("object key is not a string")
			}
			if _, exists := seen[key]; exists {
				return fmt.Errorf("duplicate object key %q", key)
			}
			seen[key] = struct{}{}
			if err := validateJSONValue(decoder); err != nil {
				return err
			}
		}
		closing, err := decoder.Token()
		if err != nil {
			return err
		}
		if closing != json.Delim('}') {
			return fmt.Errorf("object has invalid closing token %v", closing)
		}
	case '[':
		for decoder.More() {
			if err := validateJSONValue(decoder); err != nil {
				return err
			}
		}
		closing, err := decoder.Token()
		if err != nil {
			return err
		}
		if closing != json.Delim(']') {
			return fmt.Errorf("array has invalid closing token %v", closing)
		}
	default:
		return fmt.Errorf("unexpected JSON delimiter %q", delimiter)
	}
	return nil
}

func stageAndVerifyPayload(cfg Config, payload validatedPayload) (returnErr error) {
	parent := filepath.Dir(cfg.OutputDir)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return fmt.Errorf("create release-candidate parent directory: %w", err)
	}
	staging, err := os.MkdirTemp(parent, ".release-candidate-staging-")
	if err != nil {
		return fmt.Errorf("create temporary release-candidate output: %w", err)
	}
	keepStaging := false
	defer func() {
		if !keepStaging {
			if err := os.RemoveAll(staging); err != nil && returnErr == nil {
				returnErr = fmt.Errorf("clean temporary release-candidate output: %w", err)
			}
		}
	}()
	if err := os.Chmod(staging, 0o755); err != nil {
		return fmt.Errorf("set temporary release-candidate permissions: %w", err)
	}
	if err := os.WriteFile(filepath.Join(staging, ".release-candidate-output"), []byte(outputMarker), 0o644); err != nil {
		return fmt.Errorf("mark release-candidate output: %w", err)
	}
	if err := stagePayload(staging, payload); err != nil {
		return err
	}
	if err := setStagedPermissions(filepath.Join(staging, "app")); err != nil {
		return err
	}
	if err := validateStagedTree(staging); err != nil {
		return err
	}
	loaderCfg := cfg
	loaderCfg.OutputDir = staging
	if err := runLoaderChecks(loaderCfg); err != nil {
		return err
	}
	if err := validateStagedTree(staging); err != nil {
		return fmt.Errorf("loader checks left an invalid staged tree: %w", err)
	}
	if err := validateStagedPayload(staging, payload); err != nil {
		return fmt.Errorf("loader checks modified the staged payload: %w", err)
	}
	if err := clearOutput(cfg.OutputDir); err != nil {
		return err
	}
	if err := os.Rename(staging, cfg.OutputDir); err != nil {
		return fmt.Errorf("publish validated release-candidate output: %w", err)
	}
	keepStaging = true
	return nil
}

func validateStagedPayload(root string, payload validatedPayload) error {
	expected := make(map[string][]byte, len(payload.catalogs)+len(payload.benchmarks))
	for name, data := range payload.catalogs {
		expected[filepath.Join("data", filepath.FromSlash(name))] = data
	}
	for name, data := range payload.benchmarks {
		expected[filepath.Join("benchmarks", filepath.FromSlash(name))] = data
	}
	seen := map[string]struct{}{}
	appRoot := filepath.Join(root, "app")
	err := filepath.WalkDir(appRoot, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(appRoot, path)
		if err != nil {
			return err
		}
		want, exists := expected[rel]
		if !exists {
			return fmt.Errorf("unexpected file %s", rel)
		}
		got, err := readRegularFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(got, want) {
			return fmt.Errorf("file %s differs from its validated bytes", rel)
		}
		seen[rel] = struct{}{}
		return nil
	})
	if err != nil {
		return err
	}
	for rel := range expected {
		if _, exists := seen[rel]; !exists {
			return fmt.Errorf("validated file %s is missing", rel)
		}
	}
	return nil
}

func setStagedPermissions(root string) error {
	return filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		mode := os.FileMode(0o644)
		if entry.IsDir() {
			mode = 0o755
		}
		if err := os.Chmod(path, mode); err != nil {
			return fmt.Errorf("set staged payload permissions for %s: %w", path, err)
		}
		return nil
	})
}

func stagePayload(root string, payload validatedPayload) error {
	dataOutput := filepath.Join(root, "app", "data")
	benchmarkOutput := filepath.Join(root, "app", "benchmarks")
	if err := os.MkdirAll(dataOutput, 0o755); err != nil {
		return fmt.Errorf("create catalog output: %w", err)
	}
	if err := os.MkdirAll(benchmarkOutput, 0o755); err != nil {
		return fmt.Errorf("create benchmark output: %w", err)
	}
	if err := writePayloadFiles(dataOutput, payload.catalogs); err != nil {
		return err
	}
	if err := writePayloadFiles(benchmarkOutput, payload.benchmarks); err != nil {
		return err
	}
	return nil
}

func writePayloadFiles(root string, files map[string][]byte) error {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		clean := filepath.Clean(filepath.FromSlash(name))
		if clean == "." || filepath.IsAbs(clean) || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
			return fmt.Errorf("refusing unsafe staged payload path %q", name)
		}
		destination := filepath.Join(root, clean)
		if !pathContains(root, destination) {
			return fmt.Errorf("staged payload path %q escapes %s", name, root)
		}
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return fmt.Errorf("create directory for %s: %w", destination, err)
		}
		if err := os.WriteFile(destination, files[name], 0o644); err != nil {
			return fmt.Errorf("write staged file %s: %w", destination, err)
		}
		if err := os.Chmod(destination, 0o644); err != nil {
			return fmt.Errorf("set staged file permissions %s: %w", destination, err)
		}
	}
	return nil
}

func clearOutput(path string) error {
	clean := filepath.Clean(path)
	abs, err := filepath.Abs(clean)
	if err != nil {
		return fmt.Errorf("resolve output directory %q: %w", path, err)
	}
	volume := filepath.VolumeName(abs)
	if clean == "." || abs == volume+string(filepath.Separator) {
		return fmt.Errorf("refusing unsafe output directory %q", path)
	}
	if info, err := os.Lstat(clean); err == nil {
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return fmt.Errorf("refusing non-directory or symlink output path %q", path)
		}
		marker, readErr := os.ReadFile(filepath.Join(clean, ".release-candidate-output"))
		if readErr != nil || string(marker) != outputMarker {
			return fmt.Errorf("refusing to replace unmarked output directory %q", path)
		}
	} else if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("inspect output directory %s: %w", clean, err)
	}
	if err := os.RemoveAll(clean); err != nil {
		return fmt.Errorf("clean output directory %s: %w", clean, err)
	}
	return nil
}

func readRegularFile(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%s is not a regular file", path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	return data, nil
}

func validateStagedTree(root string) error {
	var problems validationErrors
	err := filepath.WalkDir(filepath.Join(root, "app"), func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			problems.add("walk staged payload %s: %v", path, walkErr)
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			problems.add("inspect staged payload %s: %v", path, err)
			return nil
		}
		perm := info.Mode().Perm()
		if entry.IsDir() {
			if perm&0o005 != 0o005 {
				problems.add("staged directory %s is not readable and traversable by arbitrary non-root users (mode %04o)", path, perm)
			}
		} else if perm&0o004 != 0o004 {
			problems.add("staged file %s is not readable by arbitrary non-root users (mode %04o)", path, perm)
		}
		return nil
	})
	problems.addErr(err)
	return problems.err()
}
